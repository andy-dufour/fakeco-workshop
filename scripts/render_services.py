#!/usr/bin/env python3
"""Write k8s/services.generated.yaml: one Deployment and one Service for each entry of services/fakeco/config.py SERVICES.

Run it after you add, remove or rename a service:  python3 scripts/render_services.py
`--check` exits 1 when the file is out of date (the tests use it)."""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "services"))
OUT = ROOT / "k8s" / "services.generated.yaml"

ONE = """apiVersion: apps/v1
kind: Deployment
metadata:
  name: {name}
  labels: {{app: {name}, fakeco/kind: {kind}}}
spec:
  replicas: 1
  strategy: {{type: Recreate}}   # a 2-vCPU Box cannot start a second copy of 22 services next to the first
  selector:
    matchLabels: {{app: {name}}}
  template:
    metadata:
      labels: {{app: {name}, fakeco/kind: {kind}}}
    spec:
      containers:
        - name: service
          image: fakeco-services:dev
          imagePullPolicy: IfNotPresent
          args: ["fakeco.run", "{name}"]
          envFrom:
            - configMapRef: {{name: fakeco}}
          env:
            - name: K8S_POD_NAME
              valueFrom: {{fieldRef: {{fieldPath: metadata.name}}}}
            - name: K8S_NAMESPACE
              valueFrom: {{fieldRef: {{fieldPath: metadata.namespace}}}}
            - {{name: OTEL_RESOURCE_ATTRIBUTES, value: "k8s.namespace.name=$(K8S_NAMESPACE),k8s.deployment.name={name},k8s.pod.name=$(K8S_POD_NAME)"}}{extra_env}
          ports: [{{containerPort: 8080}}]
          readinessProbe:
            httpGet: {{path: /healthz, port: 8080}}
            periodSeconds: 5
          resources:
            requests: {{cpu: 20m, memory: 64Mi}}
            limits: {{memory: 300Mi}}{extra_spec}
---
apiVersion: v1
kind: Service
metadata:
  name: {name}
spec:
  selector: {{app: {name}}}
  ports: [{{port: 8080, targetPort: 8080}}]
"""

# concierge-api makes the "View trace" links and the story markers with the configuration key; no other service sees a Honeycomb key
API_ENV = """
            - name: HONEYCOMB_CONFIGURATION_KEY
              valueFrom: {secretKeyRef: {name: honeycomb, key: HONEYCOMB_CONFIGURATION_KEY, optional: true}}
            - name: HONEYCOMB_API_URL
              valueFrom: {secretKeyRef: {name: honeycomb, key: HONEYCOMB_API_URL, optional: true}}"""


def render():
    from fakeco import config
    head = "# Generated by scripts/render_services.py from services/fakeco/config.py. Do not edit: change the script or config.py and run it again.\n"
    return head + "---\n".join(ONE.format(name=name, kind=kind, extra_env=API_ENV if name == "concierge-api" else "", extra_spec="")
                               for name, (kind, _module, _port) in config.SERVICES.items())


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is out of date: run python3 scripts/render_services.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT} ({text.count('kind: Deployment')} services)")


if __name__ == "__main__":
    main()
